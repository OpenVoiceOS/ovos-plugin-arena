def battle_id_for(
    modality: str, dataset_id: str, lang: str, sample_id: str,
    competitor_a: str, competitor_b: str,
) -> str:
    """Deterministic battle id — stable across assemble runs so votes stay valid.

    Competitors are sorted before hashing: the battle between (x, y) is the
    same battle as (y, x).
    """
    lo, hi = sorted((competitor_a, competitor_b))
    key = "|".join((modality, dataset_id, lang, sample_id, lo, hi))
    return hashlib.sha256(key.encode("utf-8")).hexdigest()[:16]


class Battle(BaseModel):
    """One assembled blind A/B battle, serialised into the battles pool."""

    battle_id: str
    modality: Modality
    dataset_id: str
    lang: str
    sample_id: str
    # candidate payloads — what the voter sees (NO competitor identity)
    input_text: str | None = None  # utterance (intent) / source text (tts)
    audio_url: str | None = None  # source audio clip (stt / wake_word)
    reference: str | None = None  # gold label / reference transcript
    prediction_a: Any | None = None
    prediction_b: Any | None = None
    # identity — revealed by the UI only after the vote is cast
    competitor_a: str
    competitor_b: str
    plugin_a: str = ""
    plugin_b: str = ""


class BattlesPool(BaseModel):
    """``battles-<modality>-<lang>.json`` artifact."""

    modality: Modality
    dataset_id: str
    lang: str
    generated_at: str
    dataset_info: dict[str, Any] | None = Field(
        None,
        description=(
            "Registry metadata for the eval corpus, including the "
            "paradigm-specific training corpora the fighters trained on."
        ),
    )
    battles: list[Battle] = Field(default_factory=list)
    # Count of candidate pairs dropped by assemble_battles because their
    # reference text disagreed despite sharing a sample_id (colliding legacy
    # ids across pre-#70 shards) — 0 when the assembler found none. Surfaces
    # the guard's effect instead of letting mismatched pairs vanish silently.
    skipped_reference_mismatches: int = 0



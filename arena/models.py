class PredictionRow(BaseModel):
    """One prediction for one sample by one competitor (§3.2).

    Stored as JSON lines in ``predictions/<competitor_id>.jsonl`` inside an
    HF dataset repo.  Modality-specific payload fields are kept in ``extras``
    when not modelled explicitly.
    """

    competitor_id: str
    sample_id: str
    dataset_id: str
    lang: str
    plugin_id: str
    modality: str | None = None  # league; inferred from fields when absent
    # §4 A2 schema convergence — 2 is the canonical §3.2 row contract this
    # class defines; legacy STTRow-shaped rows are converted to it at load
    # time (arena.predictions) and get schema_version 1 to mark provenance.
    schema_version: int = 2
    plugin_version: str = ""
    prediction: str | None = None
    runner_version: str = ""
    created_at: str = ""
    # intent modality
    utterance: str | None = None
    reference_intent: str | None = None
    exact_match: bool | None = None
    confidence: float | None = None
    bucket: str | None = None
    reference_slots: dict[str, str] | None = None
    predicted_slots: dict[str, str] | None = None
    # stt modality
    reference_text: str | None = None
    wer: float | None = None
    # tts modality — source text read aloud; ``prediction`` holds the audio ref
    input_text: str | None = None
    # wake_word modality — ground-truth presence ("positive"/"negative"),
    # ``prediction`` holds the detector decision
    label: str | None = None
    # audio stimulus URL for the voter (source clip for stt/wake_word;
    # synthesised clip for tts when ``prediction`` is not itself a URL)
    audio_url: str | None = None
    # shared diagnostics
    latency_ms: float | None = None
    # performance-metrics campaign M1 — additive, optional (runner.perf):
    # elapsed_ms is the wall time of the single inference call
    # (time.perf_counter-based); peak_rss_mb is a rough, process-wide RSS
    # sample bracketing that call (see runner.perf.measure_call for the
    # caveats — not a true peak, not attributable to this call alone);
    # audio_secs is the duration of the input audio (stt/wake_word) or
    # produced audio (tts), letting RTF = elapsed_ms / 1000 / audio_secs be
    # computed downstream; hw is the per-run hardware fingerprint (runner.
    # perf.hw_fingerprint). All default to None/empty — the vast majority of
    # already-published rows predate this capture and MUST stay valid.
    elapsed_ms: float | None = None
    peak_rss_mb: float | None = None
    audio_secs: float | None = None
    hw: dict[str, Any] | None = None
    extras: dict[str, Any] = Field(default_factory=dict)



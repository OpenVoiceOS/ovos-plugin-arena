from fastapi import FastAPI
from fastapi.responses import UJSONResponse

from ovos_plugin_arena.log import configure_logging
from ovos_plugin_arena.web.api.router import api_router
from ovos_plugin_arena.web.lifespan import lifespan_setup


def get_app() -> FastAPI:
    """
    Get FastAPI application.

    This is the main constructor of an application.

    :return: application.
    """
    configure_logging()
    app = FastAPI(
        title="ovos_plugin_arena",
        lifespan=lifespan_setup,
        docs_url="/api/docs",
        redoc_url="/api/redoc",
        openapi_url="/api/openapi.json",
        default_response_class=UJSONResponse,
    )

    # Main router for the API.
    app.include_router(router=api_router, prefix="/api")

    return app
